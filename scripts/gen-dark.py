#!/usr/bin/env python3
"""Generates src/renderer/theme.css (dark palette) from studio.css. Run after editing studio.css colours."""
import re, colorsys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'src/renderer'
css = re.sub(r'/\*.*?\*/', '', (root / 'studio.css').read_text(), flags=re.S)
P = 'html:not([data-theme=light])'
HUE = 218 / 360

def parse(h):
    h = h[1:]
    if len(h) in (3, 4): h = ''.join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    a = h[6:8]
    hh, l, s = colorsys.rgb_to_hls(r, g, b)
    return hh, l, s, a

def out(hh, l, s, a):
    r, g, b = colorsys.hls_to_rgb(hh, max(0, min(1, l)), max(0, min(1, s)))
    return '#%02x%02x%02x%s' % (round(r * 255), round(g * 255), round(b * 255), a)

def tone(hh, s):
    # near-neutral colours are re-tinted navy so the whole UI shares one hue family
    return (HUE, 0.28) if s < 0.3 else (hh, min(s, 0.45))

def bg(m):
    hh, l, s, a = parse(m.group())
    if l < 0.62: return m.group()
    hh, s = tone(hh, s)
    nl = 0.12 if l >= 0.985 else min(0.08 + (0.985 - l) * 0.9, 0.45)
    return out(hh, nl, s, a)

def border(m):
    hh, l, s, a = parse(m.group())
    if l < 0.62: return m.group()
    hh, s = tone(hh, s)
    return out(hh, 0.2 + (1 - l) * 0.4, s * 0.8, a)

def text(m):
    hh, l, s, a = parse(m.group())
    if l >= 0.55: return m.group()
    if s > 0.5: return out(hh, max(l, 0.62), min(s, 0.7), a)
    hh, s = tone(hh, s)
    return out(hh, 0.97 - l * 0.6, s * 0.6, a)

HEX = re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b')
def convert(prop, value):
    p = prop.strip().lower()
    if p == 'color': f = text
    elif p.startswith('background'): f = bg
    elif p.startswith('border') or p.startswith('outline'): f = border
    else: return None
    new = HEX.sub(f, value)
    return new if new != value else None

def block(i):
    """returns (end index of matching brace)"""
    d = 0
    for j in range(i, len(css)):
        if css[j] == '{': d += 1
        elif css[j] == '}':
            d -= 1
            if d == 0: return j
    raise SystemExit('unbalanced')

def prefix(sel):
    parts = []
    for s in sel.split(','):
        s = s.strip()
        if not s: continue
        if s.startswith(':root') or s == 'html': parts.append(P + s.replace(':root', '', 1))
        elif s.startswith('body'): parts.append(P + ' ' + s)
        else: parts.append(P + ' ' + s)
    return ','.join(parts)

def walk(text_, base):
    res, i = [], 0
    while i < len(text_):
        m = re.compile(r'\s*([^{}]+)\{').match(text_, i)
        if not m: break
        sel = m.group(1).strip()
        start = m.end() - 1
        d, j = 0, start
        while True:
            if text_[j] == '{': d += 1
            elif text_[j] == '}':
                d -= 1
                if d == 0: break
            j += 1
        body = text_[start + 1:j]
        if sel.startswith('@media'):
            inner = walk(body, base)
            if inner: res.append(sel + '{' + inner + '}')
        elif sel.startswith('@'):
            pass
        else:
            decls = []
            for d_ in re.split(r';(?![^()]*\))', body):
                if ':' not in d_: continue
                k, v = d_.split(':', 1)
                nv = convert(k, v)
                if nv: decls.append(f'{k.strip()}:{nv.strip()}')
            if decls: res.append(prefix(sel) + '{' + ';'.join(decls) + '}')
        i = j + 1
    return '\n'.join(res)

base = f"""/* GENERATED by scripts/gen-dark.py from studio.css. Do not edit by hand. */
{P}{{color-scheme:dark;color:#d9e2f1;background:#0b111c;--teal:#35c9b3;--line:#27334b;--muted:#8a97b0;--dark:#e6edf8}}
{P} body{{background:#0b111c;color:#d9e2f1}}
{P} ::selection{{background:#2fe0b855}}
{P} ::-webkit-scrollbar{{width:10px;height:10px}}{P} ::-webkit-scrollbar-thumb{{background:#2a3752;border-radius:6px}}{P} ::-webkit-scrollbar-track{{background:transparent}}
{P} input,{P} textarea,{P} select{{background:#0f1726;color:#e6edf8;border-color:#2a3752}}
{P} input::placeholder,{P} textarea::placeholder{{color:#6b7a95}}
{P} input:focus,{P} textarea:focus,{P} select:focus{{border-color:#35c9b3;outline-color:#35c9b3}}
{P} button:disabled{{opacity:.45}}
{P} .modal-backdrop{{background:#02060dcc}}
{P} .modal{{box-shadow:0 30px 80px -20px #000}}
{P} .tpl-card:hover:not(:disabled){{border-color:#35c9b3}}
"""
extra = """
.theme-toggle{width:100%;margin-top:6px}
.tpl-grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(230px,1fr));gap:10px}
.tpl-card{display:grid;gap:6px;text-align:right;padding:14px;border-radius:12px;align-content:start}
.tpl-card span:first-child{font-size:24px}.tpl-card small{line-height:1.7}
"""
(root / 'theme.css').write_text(base + walk(css, '') + '\n' + extra)
